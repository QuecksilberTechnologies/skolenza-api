/*
  Data-preserving City -> Locality migration.

  Result:
  - skolenza."City" becomes skolenza."Locality".
  - Existing rows are classified as City and linked to their matching District.
  - LocalityType is seeded with City, Town, Village, and Other / Unclassified.
  - Campus receives DistrictId; its existing CityId column is retained as
    the physical compatibility column used by LocalityId in the updated API.
  - A read-compatible City view keeps the currently deployed API operational
    during the deployment transition.
*/

BEGIN;
SET LOCAL lock_timeout = '15s';
SET LOCAL statement_timeout = '180s';

CREATE TABLE IF NOT EXISTS skolenza."LocalityType"
(
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TypeName" character varying(30) NOT NULL,
    "IsActive" boolean NOT NULL DEFAULT TRUE,
    CONSTRAINT "UQ_LocalityType_TypeName" UNIQUE ("TypeName")
);

INSERT INTO skolenza."LocalityType" ("Id", "TypeName", "IsActive")
VALUES
    (1, 'City', TRUE),
    (2, 'Town', TRUE),
    (3, 'Village', TRUE),
    (4, 'Other / Unclassified', TRUE)
ON CONFLICT ("Id") DO UPDATE
SET "TypeName" = EXCLUDED."TypeName",
    "IsActive" = TRUE;

DO $$
BEGIN
    IF to_regclass('skolenza."Locality"') IS NULL
       AND EXISTS
       (
           SELECT 1
           FROM pg_class class
           JOIN pg_namespace namespace ON namespace.oid = class.relnamespace
           WHERE namespace.nspname = 'skolenza'
             AND class.relname = 'City'
             AND class.relkind = 'r'
       ) THEN
        ALTER TABLE skolenza."City" RENAME TO "Locality";
    END IF;

    IF to_regclass('skolenza."Locality"') IS NULL THEN
        RAISE EXCEPTION 'Neither skolenza.City table nor skolenza.Locality table exists.';
    END IF;

    IF EXISTS
       (
           SELECT 1 FROM information_schema.columns
           WHERE table_schema = 'skolenza' AND table_name = 'Locality' AND column_name = 'CityName'
       ) THEN
        ALTER TABLE skolenza."Locality" RENAME COLUMN "CityName" TO "LocalityName";
    END IF;
END;
$$;

ALTER TABLE skolenza."Locality"
    ADD COLUMN IF NOT EXISTS "DistrictId" integer,
    ADD COLUMN IF NOT EXISTS "LocalityTypeId" integer;

UPDATE skolenza."Locality" locality
SET "DistrictId" = district."Id"
FROM skolenza."District" district
WHERE locality."DistrictId" IS NULL
  AND district."Id" = locality."Id"
  AND district."StateId" = locality."StateId";

-- Legacy catalogues may contain cities for a state before that state's district
-- catalogue has been loaded. Preserve those rows under one explicit holding
-- district per state instead of guessing a real-world district or deleting data.
SELECT setval(
    pg_get_serial_sequence('skolenza."District"', 'Id'),
    COALESCE((SELECT max("Id") FROM skolenza."District"), 0) + 1,
    false
);

INSERT INTO skolenza."District"
("StateId", "DistrictName", "IsActive", "Remark", "AddedById", "AddedDateTime")
SELECT DISTINCT locality."StateId",
       'Unassigned / Legacy',
       TRUE,
       'Created by City-to-Locality migration for legacy rows awaiting district classification.',
       1,
       CURRENT_TIMESTAMP
FROM skolenza."Locality" locality
WHERE locality."DistrictId" IS NULL
  AND NOT EXISTS
  (
      SELECT 1
      FROM skolenza."District" district
      WHERE district."StateId" = locality."StateId"
        AND lower(btrim(district."DistrictName")) = 'unassigned / legacy'
  );

UPDATE skolenza."Locality" locality
SET "DistrictId" = district."Id"
FROM skolenza."District" district
WHERE locality."DistrictId" IS NULL
  AND district."StateId" = locality."StateId"
  AND lower(btrim(district."DistrictName")) = 'unassigned / legacy';

DO $$
DECLARE
    unmapped_count bigint;
BEGIN
    SELECT count(*) INTO unmapped_count
    FROM skolenza."Locality"
    WHERE "DistrictId" IS NULL;

    IF unmapped_count > 0 THEN
        RAISE EXCEPTION '% Locality row(s) cannot be mapped to District by the synchronized Id/StateId catalog.', unmapped_count;
    END IF;
END;
$$;

UPDATE skolenza."Locality"
SET "LocalityTypeId" = 1
WHERE "LocalityTypeId" IS NULL;

ALTER TABLE skolenza."Locality"
    ALTER COLUMN "DistrictId" SET NOT NULL,
    ALTER COLUMN "LocalityTypeId" SET NOT NULL,
    ALTER COLUMN "LocalityTypeId" SET DEFAULT 1;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Locality_District') THEN
        ALTER TABLE skolenza."Locality"
            ADD CONSTRAINT "FK_Locality_District"
            FOREIGN KEY ("DistrictId") REFERENCES skolenza."District"("Id") ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Locality_LocalityType') THEN
        ALTER TABLE skolenza."Locality"
            ADD CONSTRAINT "FK_Locality_LocalityType"
            FOREIGN KEY ("LocalityTypeId") REFERENCES skolenza."LocalityType"("Id") ON DELETE RESTRICT;
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS "IX_Locality_DistrictId" ON skolenza."Locality" ("DistrictId");
CREATE INDEX IF NOT EXISTS "IX_Locality_LocalityTypeId" ON skolenza."Locality" ("LocalityTypeId");

ALTER TABLE skolenza."Campus"
    ADD COLUMN IF NOT EXISTS "DistrictId" integer;

UPDATE skolenza."Campus" institution_location
SET "DistrictId" = locality."DistrictId"
FROM skolenza."Locality" locality
WHERE institution_location."DistrictId" IS NULL
  AND institution_location."CityId" = locality."Id";

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Campus_District') THEN
        ALTER TABLE skolenza."Campus"
            ADD CONSTRAINT "FK_Campus_District"
            FOREIGN KEY ("DistrictId") REFERENCES skolenza."District"("Id") ON DELETE RESTRICT;
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS "IX_Campus_DistrictId"
    ON skolenza."Campus" ("DistrictId");

DO $$
BEGIN
    IF to_regclass('skolenza."City"') IS NULL THEN
        EXECUTE '
            CREATE VIEW skolenza."City" AS
            SELECT "Id", "LocalityName" AS "CityName", "StateId", "IsActive"
            FROM skolenza."Locality"';
    END IF;
END;
$$;

COMMIT;

SELECT "Id", "TypeName", "IsActive"
FROM skolenza."LocalityType"
ORDER BY "Id";

SELECT
    count(*) AS "LocalityCount",
    count(*) FILTER (WHERE "DistrictId" IS NULL) AS "MissingDistrictCount",
    count(*) FILTER (WHERE "LocalityTypeId" IS NULL) AS "MissingLocalityTypeCount"
FROM skolenza."Locality";
