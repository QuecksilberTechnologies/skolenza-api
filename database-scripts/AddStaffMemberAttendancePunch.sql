BEGIN;

ALTER TABLE skolenza."AttendanceDeviceType"
    ADD COLUMN IF NOT EXISTS "DeviceTypeCode" character varying(30);

INSERT INTO skolenza."AttendanceDeviceType"
    ("DeviceTypeCode", "DeviceType", "Remark", "IsActive", "IsDeviceRegister", "AddedById", "AddedDateTime")
SELECT seed."Code", seed."Name", seed."Remark", TRUE, seed."RequiresRegistration", 1, CURRENT_TIMESTAMP
FROM (VALUES
    ('MOBILE', 'Mobile', 'Attendance marked from an authenticated mobile client.', FALSE),
    ('WEB', 'Web', 'Attendance marked from an authenticated web client.', FALSE),
    ('BIOMETRIC', 'Biometric Device', 'Attendance received from a registered physical attendance device.', TRUE),
    ('MANUAL', 'Manual Entry', 'Attendance entered by an authorized administrator.', FALSE)
) AS seed("Code", "Name", "Remark", "RequiresRegistration")
WHERE NOT EXISTS (
    SELECT 1 FROM skolenza."AttendanceDeviceType" existing
    WHERE upper(btrim(existing."DeviceTypeCode")) = seed."Code");

ALTER TABLE skolenza."AttendanceDeviceType"
    ALTER COLUMN "DeviceTypeCode" SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "UX_AttendanceDeviceType_DeviceTypeCode"
    ON skolenza."AttendanceDeviceType" (upper(btrim("DeviceTypeCode")));

CREATE TABLE IF NOT EXISTS skolenza."StaffMemberAttendancePunch"
(
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InstitutionId" bigint NOT NULL,
    "StaffMemberId" bigint NOT NULL,
    "StaffMemberWorkArrangementId" bigint NOT NULL,
    "PolicyVersionId" bigint NOT NULL,
    "CampusId" bigint NULL,
    "WorkDate" date NOT NULL,
    "OccurredAtUtc" timestamp with time zone NOT NULL,
    "ClientOccurredAt" timestamp with time zone NULL,
    "AttendanceDeviceTypeId" integer NOT NULL,
    "PunchAction" smallint NOT NULL,
    "Latitude" numeric(10,7) NULL,
    "Longitude" numeric(10,7) NULL,
    "AccuracyMeters" numeric(10,2) NULL,
    "DistanceFromLocationMeters" numeric(12,2) NULL,
    "IdempotencyKey" uuid NOT NULL,
    "AddedById" bigint NOT NULL,
    "AddedDateTime" timestamp with time zone NOT NULL,
    CONSTRAINT "CK_StaffMemberAttendancePunch_Action" CHECK ("PunchAction" BETWEEN 1 AND 2),
    CONSTRAINT "CK_StaffMemberAttendancePunch_Latitude" CHECK ("Latitude" IS NULL OR "Latitude" BETWEEN -90 AND 90),
    CONSTRAINT "CK_StaffMemberAttendancePunch_Longitude" CHECK ("Longitude" IS NULL OR "Longitude" BETWEEN -180 AND 180),
    CONSTRAINT "FK_StaffMemberAttendancePunch_Institution" FOREIGN KEY ("InstitutionId") REFERENCES skolenza."Institution" ("Id"),
    CONSTRAINT "FK_StaffMemberAttendancePunch_StaffMember" FOREIGN KEY ("StaffMemberId") REFERENCES skolenza."StaffMember" ("Id"),
    CONSTRAINT "FK_StaffMemberAttendancePunch_Arrangement" FOREIGN KEY ("StaffMemberWorkArrangementId") REFERENCES skolenza."StaffMemberWorkArrangement" ("Id"),
    CONSTRAINT "FK_StaffMemberAttendancePunch_PolicyVersion" FOREIGN KEY ("PolicyVersionId") REFERENCES skolenza."PolicyVersion" ("Id"),
    CONSTRAINT "FK_StaffMemberAttendancePunch_Location" FOREIGN KEY ("CampusId") REFERENCES skolenza."Campus" ("Id"),
    CONSTRAINT "FK_StaffMemberAttendancePunch_AttendanceDeviceType" FOREIGN KEY ("AttendanceDeviceTypeId") REFERENCES skolenza."AttendanceDeviceType" ("Id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_StaffMemberAttendancePunch_Idempotency"
    ON skolenza."StaffMemberAttendancePunch" ("InstitutionId", "StaffMemberId", "IdempotencyKey");
CREATE INDEX IF NOT EXISTS "IX_StaffMemberAttendancePunch_DayTimeline"
    ON skolenza."StaffMemberAttendancePunch" ("InstitutionId", "StaffMemberId", "WorkDate", "OccurredAtUtc", "Id");

COMMIT;
