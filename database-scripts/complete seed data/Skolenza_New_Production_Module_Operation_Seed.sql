-- Preserve existing module IDs and every dependent permission/entitlement row
-- while moving legacy leaf codes to their canonical singular identities.
DO $canonical_institution_master_leaf_codes$
DECLARE
    identity record;
    legacy_id integer;
    canonical_id integer;
BEGIN
    FOR identity IN
        SELECT * FROM (VALUES
            ('INSTITUTION_DEPARTMENTS','DEPARTMENT'),
            ('INSTITUTION_DESIGNATIONS','DESIGNATION'),
            ('INSTITUTION_ROLES_PERMISSIONS','ROLE'),
            ('INSTITUTION_STAFF_MEMBER_TYPES','STAFF_MEMBER_TYPE')
        ) AS codes(legacy_code,canonical_code)
    LOOP
        SELECT "Id" INTO legacy_id
        FROM skolenza."Module"
        WHERE "ModuleCode"=identity.legacy_code
        ORDER BY "Id" LIMIT 1;

        SELECT "Id" INTO canonical_id
        FROM skolenza."Module"
        WHERE "ModuleCode"=identity.canonical_code
        ORDER BY "Id" LIMIT 1;

        IF legacy_id IS NOT NULL AND canonical_id IS NOT NULL
           AND legacy_id <> canonical_id THEN
            RAISE EXCEPTION
                'Conflicting module rows exist for legacy code % and canonical code %. Resolve before seeding.',
                identity.legacy_code, identity.canonical_code;
        END IF;

        IF legacy_id IS NOT NULL AND canonical_id IS NULL THEN
            UPDATE skolenza."Module"
            SET "ModuleCode"=identity.canonical_code,
                "UpdatedById"=1,
                "UpdatedDateTime"=CURRENT_TIMESTAMP
            WHERE "Id"=legacy_id;
        END IF;
    END LOOP;
END $canonical_institution_master_leaf_codes$;

