$$
DECLARE
    staffMember_list_plan_count INTEGER;
    target_module_count INTEGER;
BEGIN
    SELECT COUNT(DISTINCT source."SubscriptionPlanId")
    INTO staffMember_list_plan_count
    FROM skolenza."PlanModuleMapping" source
    INNER JOIN skolenza."Module" source_module
        ON source_module."Id" = source."ModuleId"
    WHERE source_module."ModuleCode" = 'STAFF_DIRECTORY'
      AND source."IsActive" = TRUE;

    IF staffMember_list_plan_count = 0 THEN
        RAISE NOTICE
            'No active STAFF_DIRECTORY PlanModuleMapping exists. Institution feature plan inheritance is intentionally skipped.';
    END IF;

    SELECT COUNT(*)
    INTO target_module_count
    FROM skolenza."Module" target_module
    WHERE target_module."ModuleCode" IN
          (
              'INSTITUTION_EMAIL_CONFIG',
              'INSTITUTION_LOCATIONS',
              'INSTITUTION_DEVICE_SETUP',
              'INSTITUTION_DEVICE_CONFIGURATION',
              'EMP_DEVICES',
              'EMP_WORK_LOCATIONS',
              'EMP_WORK_ARRANGEMENT',
              'EMP_WORK_PATTERN',
              'EMP_OVERRIDES'
          )
      AND target_module."ModuleScope" = 1
      AND target_module."IsActive" = TRUE;

    IF target_module_count <> 9 THEN
        RAISE EXCEPTION
            'Expected nine active Institution feature modules before plan inheritance; found %.',
            target_module_count;
    END IF;

    INSERT INTO skolenza."PlanModuleMapping"
    (
        "SubscriptionPlanId", "ModuleId", "IsActive", "Remark",
        "AddedById", "AddedDateTime", "UpdatedById", "UpdatedDateTime"
