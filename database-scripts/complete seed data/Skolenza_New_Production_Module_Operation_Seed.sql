        1,
        CURRENT_TIMESTAMP
    FROM skolenza."PlanModuleMapping" source
    INNER JOIN skolenza."Module" source_module
        ON source_module."Id" = source."ModuleId"
       AND source_module."ModuleCode" = 'STAFF_DIRECTORY'
    INNER JOIN skolenza."Module" target_module
        ON target_module."ModuleCode" IN
