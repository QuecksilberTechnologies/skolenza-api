-- SECTION 8B
-- INSTITUTION PLATFORM FEATURE PLAN INHERITANCE
-- ============================================================================
-- A Institution entitlement is sourced only from an active PlanModuleMapping.
-- These baseline Institution features inherit precisely the active plan coverage of
-- STAFF_DIRECTORY. This is the established baseline module already present in plans;
-- Host-only modules are deliberately not assigned to any Subscription Plan.
-- Existing mappings are never altered, so a Host's later plan-specific choice
