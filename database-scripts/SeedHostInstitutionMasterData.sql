BEGIN;

-- The original five platform categories used fixed identifiers. Host CRUD needs the same
-- authoritative table to allocate subsequent identifiers without application-side MAX(Id) races.
DO $$
DECLARE next_id bigint;
BEGIN
 IF NOT EXISTS (
  SELECT 1
  FROM pg_attribute attribute
  WHERE attribute.attrelid = 'skolenza."StaffCategory"'::regclass
    AND attribute.attname = 'Id'
    AND attribute.attidentity IN ('a', 'd')
 ) THEN
  SELECT COALESCE(MAX("Id"), 0) + 1 INTO next_id FROM skolenza."StaffCategory";
  EXECUTE format(
   'ALTER TABLE skolenza."StaffCategory" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
   next_id);
 END IF;
END $$;

-- Host-only parent for centrally governed catalogues shared by every Institution.
INSERT INTO skolenza."Module"
("InstitutionId","ModuleCode","ModuleName","PageName","DisplayName","URLPath","ParentModuleId",
 "IsLeafNode","IsModuleDisplayInUI","IsCommonMenu","ModuleScope","IsActive","ImageIconWeb",
 "ImageIconMobile","ItemPriority","Remark","AddedById","AddedDateTime")
SELECT NULL,'HOST_INSTITUTION_MASTER_DATA','Host-Institution-Master-Data','host-institution-master-data',
       'Institution Master Data',NULL,NULL,FALSE,TRUE,FALSE,2,TRUE,'bi bi-database-gear','database',120,
       'Host-owned master catalogues consumed by Institutions.',1,CURRENT_TIMESTAMP
WHERE NOT EXISTS (SELECT 1 FROM skolenza."Module" WHERE "ModuleCode"='HOST_INSTITUTION_MASTER_DATA');

UPDATE skolenza."Module" SET "ModuleName"='Host-Institution-Master-Data',
"PageName"='host-institution-master-data',"DisplayName"='Institution Master Data',"URLPath"=NULL,
"ParentModuleId"=NULL,"IsLeafNode"=FALSE,"IsModuleDisplayInUI"=TRUE,"IsCommonMenu"=FALSE,
"ModuleScope"=2,"IsActive"=TRUE,"ImageIconWeb"='bi bi-database-gear',"ImageIconMobile"='database',
"ItemPriority"=120,"Remark"='Host-owned master catalogues consumed by Institutions.',
"UpdatedById"=1,"UpdatedDateTime"=CURRENT_TIMESTAMP
WHERE "ModuleCode"='HOST_INSTITUTION_MASTER_DATA';

INSERT INTO skolenza."Module"
("InstitutionId","ModuleCode","ModuleName","PageName","DisplayName","URLPath","ParentModuleId",
 "IsLeafNode","IsModuleDisplayInUI","IsCommonMenu","ModuleScope","IsActive","ImageIconWeb",
 "ImageIconMobile","ItemPriority","Remark","AddedById","AddedDateTime")
SELECT NULL,'HOST_STAFF_CATEGORY_CATALOGUE','Host-Staff-Category-Catalogue','staff-category-catalogue',
       'Staff Category Catalogue','/app/institution-master-data/staff-categories',parent."Id",TRUE,TRUE,
       FALSE,2,TRUE,'bi bi-people','groups',10,'Platform Staff Category catalogue.',1,CURRENT_TIMESTAMP
FROM skolenza."Module" parent
WHERE parent."ModuleCode"='HOST_INSTITUTION_MASTER_DATA' AND parent."ModuleScope"=2
AND NOT EXISTS (SELECT 1 FROM skolenza."Module" WHERE "ModuleCode"='HOST_STAFF_CATEGORY_CATALOGUE');

UPDATE skolenza."Module" child SET "ModuleName"='Host-Staff-Category-Catalogue',
"PageName"='staff-category-catalogue',"DisplayName"='Staff Category Catalogue',
"URLPath"='/app/institution-master-data/staff-categories',"ParentModuleId"=parent."Id",
"IsLeafNode"=TRUE,"IsModuleDisplayInUI"=TRUE,"IsCommonMenu"=FALSE,"ModuleScope"=2,"IsActive"=TRUE,
"ImageIconWeb"='bi bi-people',"ImageIconMobile"='groups',"ItemPriority"=10,
"Remark"='Platform Staff Category catalogue.',"UpdatedById"=1,"UpdatedDateTime"=CURRENT_TIMESTAMP
FROM skolenza."Module" parent
WHERE child."ModuleCode"='HOST_STAFF_CATEGORY_CATALOGUE'
AND parent."ModuleCode"='HOST_INSTITUTION_MASTER_DATA' AND parent."ModuleScope"=2;

INSERT INTO skolenza."ModuleOperationMapping"
("ModuleId","OperationId","PageURL","IconURL","IsCommonItem","IsOperational","Priority","Remark",
 "IsActive","AddedById","AddedDateTime")
SELECT module."Id",operation."Id",module."URLPath",COALESCE(operation."IconImage",module."ImageIconWeb"),
       FALSE,TRUE,CASE operation."OperationName" WHEN 'View' THEN 10 WHEN 'Add' THEN 20 ELSE 30 END,
       operation."OperationName"||' Staff Category Catalogue.',TRUE,1,CURRENT_TIMESTAMP
FROM skolenza."Module" module
JOIN skolenza."Operation" operation ON operation."OperationName" IN ('View','Add','Update') AND operation."IsActive"=TRUE
WHERE module."ModuleCode"='HOST_STAFF_CATEGORY_CATALOGUE'
AND NOT EXISTS (SELECT 1 FROM skolenza."ModuleOperationMapping" existing
                WHERE existing."ModuleId"=module."Id" AND existing."OperationId"=operation."Id");

UPDATE skolenza."ModuleOperationMapping" mapping SET "PageURL"=module."URLPath","IsOperational"=TRUE,
"IsActive"=TRUE,"UpdatedById"=1,"UpdatedDateTime"=CURRENT_TIMESTAMP
FROM skolenza."Module" module JOIN skolenza."Operation" operation
ON operation."OperationName" IN ('View','Add','Update')
WHERE module."ModuleCode"='HOST_STAFF_CATEGORY_CATALOGUE' AND mapping."ModuleId"=module."Id"
AND mapping."OperationId"=operation."Id";

INSERT INTO skolenza."HostRoleModuleAndPermission"
("HostRoleId","ModuleId","OperationId","IsActive","IsSoftDeleted","AddedById","AddedDateTime")
SELECT role."Id",module."Id",operation."Id",TRUE,FALSE,1,CURRENT_TIMESTAMP
FROM skolenza."HostRole" role
JOIN skolenza."Module" module ON module."ModuleCode"='HOST_STAFF_CATEGORY_CATALOGUE'
JOIN skolenza."Operation" operation ON operation."OperationName" IN ('View','Add','Update') AND operation."IsActive"=TRUE
WHERE role."Name"='Host-Super-Admin' AND role."IsActive"=TRUE AND role."IsSoftDeleted"=FALSE
AND NOT EXISTS (SELECT 1 FROM skolenza."HostRoleModuleAndPermission" permission
                WHERE permission."HostRoleId"=role."Id" AND permission."ModuleId"=module."Id"
                AND permission."OperationId"=operation."Id");

DO $$ BEGIN
 IF (SELECT COUNT(*) FROM skolenza."Module" WHERE "ModuleCode"='HOST_INSTITUTION_MASTER_DATA' AND "ModuleScope"=2 AND "IsActive") <> 1 THEN
  RAISE EXCEPTION 'Host Institution Master Data parent validation failed.';
 END IF;
 IF (SELECT COUNT(*) FROM skolenza."Module" child JOIN skolenza."Module" parent ON parent."Id"=child."ParentModuleId"
     WHERE child."ModuleCode"='HOST_STAFF_CATEGORY_CATALOGUE' AND child."ModuleScope"=2
     AND parent."ModuleCode"='HOST_INSTITUTION_MASTER_DATA') <> 1 THEN
  RAISE EXCEPTION 'Staff Category Catalogue child validation failed.';
 END IF;
END $$;

COMMIT;
