-- Additive foundation for immutable fee-head snapshots. Existing quotes are not backfilled.
-- Reconcile historical quotes before exposing or allocating their head balances.
BEGIN;
LOCK TABLE skolenza."StudentAdmissionFeeQuote" IN SHARE MODE;
DO $$
BEGIN
    IF to_regclass('skolenza."StudentFeeInstallmentHead"') IS NULL
       AND EXISTS (SELECT 1 FROM skolenza."StudentAdmissionFeeQuote") THEN
        RAISE EXCEPTION 'Existing fee quotes require an explicitly verified head snapshot migration before enabling this table.';
    END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS "AK_StudentFeeInstallment_TenantQuote"
    ON skolenza."StudentFeeInstallment" ("Id", "InstitutionId", "StudentAdmissionFeeQuoteId");
CREATE UNIQUE INDEX IF NOT EXISTS "AK_StudentAdmissionFeeQuoteLine_TenantQuote"
    ON skolenza."StudentAdmissionFeeQuoteLine" ("Id", "InstitutionId", "StudentAdmissionFeeQuoteId");
CREATE TABLE IF NOT EXISTS skolenza."StudentFeeInstallmentHead" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InstitutionId" bigint NOT NULL,
    "StudentAdmissionFeeQuoteId" bigint NOT NULL,
    "StudentFeeInstallmentId" bigint NOT NULL,
    "StudentAdmissionFeeQuoteLineId" bigint NOT NULL,
    "ScheduledAmount" numeric(18,3) NOT NULL,
    CONSTRAINT "CK_StudentFeeInstallmentHead_Amount" CHECK ("ScheduledAmount" > 0),
    CONSTRAINT "FK_StudentFeeInstallmentHead_Installment" FOREIGN KEY ("StudentFeeInstallmentId", "InstitutionId", "StudentAdmissionFeeQuoteId")
        REFERENCES skolenza."StudentFeeInstallment"("Id", "InstitutionId", "StudentAdmissionFeeQuoteId") ON DELETE RESTRICT,
    CONSTRAINT "FK_StudentFeeInstallmentHead_QuoteLine" FOREIGN KEY ("StudentAdmissionFeeQuoteLineId", "InstitutionId", "StudentAdmissionFeeQuoteId")
        REFERENCES skolenza."StudentAdmissionFeeQuoteLine"("Id", "InstitutionId", "StudentAdmissionFeeQuoteId") ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_StudentFeeInstallmentHead_Installment_QuoteLine"
    ON skolenza."StudentFeeInstallmentHead" ("InstitutionId", "StudentFeeInstallmentId", "StudentAdmissionFeeQuoteLineId");
COMMIT;
