BEGIN;

CREATE TABLE IF NOT EXISTS skolenza."AcademicWorkflowStatusMaster" (
    "Id" smallint PRIMARY KEY,
    "Code" varchar(40) NOT NULL UNIQUE,
    "Name" varchar(80) NOT NULL,
    "DisplayOrder" smallint NOT NULL,
    "IsActive" boolean NOT NULL DEFAULT true
);

INSERT INTO skolenza."AcademicWorkflowStatusMaster" ("Id", "Code", "Name", "DisplayOrder", "IsActive") VALUES
    (1, 'DRAFT', 'Draft', 1, true),
    (2, 'SUBMITTED', 'Submitted for approval', 2, true),
    (3, 'APPROVED', 'Approved', 3, true),
    (4, 'REJECTED', 'Rejected', 4, true),
    (5, 'COMPLETED', 'Completed', 5, true),
    (6, 'CANCELLED', 'Cancelled', 6, true)
ON CONFLICT ("Id") DO UPDATE SET "Code" = EXCLUDED."Code", "Name" = EXCLUDED."Name", "DisplayOrder" = EXCLUDED."DisplayOrder", "IsActive" = EXCLUDED."IsActive";

CREATE TABLE IF NOT EXISTS skolenza."CurriculumFrameworkMaster" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "InstitutionId" bigint NOT NULL,
    "Code" varchar(60) NOT NULL, "Name" varchar(150) NOT NULL, "Description" varchar(500),
    "IsActive" boolean NOT NULL DEFAULT true, "IsSoftDeleted" boolean NOT NULL DEFAULT false,
    "AddedById" bigint NOT NULL, "AddedDateTime" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedById" bigint, "UpdatedDateTime" timestamp without time zone,
    "AcademicSessionId" bigint NOT NULL, "AuthorityName" varchar(150) NOT NULL, "Version" varchar(60) NOT NULL,
    "EffectiveFrom" date NOT NULL, "EffectiveTo" date, "WorkflowStatusId" smallint NOT NULL,
    "ReviewedById" bigint, "ReviewedDateTime" timestamp without time zone, "ReviewRemark" varchar(500),
    CONSTRAINT "FK_CurriculumFramework_AcademicSession" FOREIGN KEY ("AcademicSessionId") REFERENCES skolenza."AcademicSessionMaster"("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_CurriculumFramework_Status" FOREIGN KEY ("WorkflowStatusId") REFERENCES skolenza."AcademicWorkflowStatusMaster"("Id") ON DELETE RESTRICT,
    CONSTRAINT "UQ_CurriculumFramework_Institution_Code" UNIQUE ("InstitutionId", "Code")
);

CREATE TABLE IF NOT EXISTS skolenza."CurriculumUnit" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "InstitutionId" bigint NOT NULL,
    "Code" varchar(60) NOT NULL, "Name" varchar(150) NOT NULL, "Description" varchar(500),
    "IsActive" boolean NOT NULL DEFAULT true, "IsSoftDeleted" boolean NOT NULL DEFAULT false,
    "AddedById" bigint NOT NULL, "AddedDateTime" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedById" bigint, "UpdatedDateTime" timestamp without time zone,
    "CurriculumFrameworkId" bigint NOT NULL, "CourseOfferingId" bigint NOT NULL, "ParentCurriculumUnitId" bigint,
    "Sequence" smallint NOT NULL, "PlannedPeriods" smallint NOT NULL, "LearningOutcome" varchar(1000),
    CONSTRAINT "FK_CurriculumUnit_Framework" FOREIGN KEY ("CurriculumFrameworkId") REFERENCES skolenza."CurriculumFrameworkMaster"("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_CurriculumUnit_Offering" FOREIGN KEY ("CourseOfferingId") REFERENCES skolenza."CourseOfferingMaster"("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_CurriculumUnit_Parent" FOREIGN KEY ("ParentCurriculumUnitId") REFERENCES skolenza."CurriculumUnit"("Id") ON DELETE RESTRICT,
    CONSTRAINT "UQ_CurriculumUnit_Framework_Code" UNIQUE ("InstitutionId", "CurriculumFrameworkId", "Code"),
    CONSTRAINT "CK_CurriculumUnit_PlannedPeriods" CHECK ("PlannedPeriods" > 0)
);

CREATE TABLE IF NOT EXISTS skolenza."CurriculumTopic" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "InstitutionId" bigint NOT NULL,
    "Code" varchar(60) NOT NULL, "Name" varchar(150) NOT NULL, "Description" varchar(500),
    "IsActive" boolean NOT NULL DEFAULT true, "IsSoftDeleted" boolean NOT NULL DEFAULT false,
    "AddedById" bigint NOT NULL, "AddedDateTime" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedById" bigint, "UpdatedDateTime" timestamp without time zone,
    "CurriculumUnitId" bigint NOT NULL, "Sequence" smallint NOT NULL, "PlannedPeriods" smallint NOT NULL, "LearningOutcome" varchar(1000),
    CONSTRAINT "FK_CurriculumTopic_Unit" FOREIGN KEY ("CurriculumUnitId") REFERENCES skolenza."CurriculumUnit"("Id") ON DELETE RESTRICT,
    CONSTRAINT "UQ_CurriculumTopic_Unit_Code" UNIQUE ("InstitutionId", "CurriculumUnitId", "Code"),
    CONSTRAINT "CK_CurriculumTopic_PlannedPeriods" CHECK ("PlannedPeriods" > 0)
);

CREATE TABLE IF NOT EXISTS skolenza."LessonPlan" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "InstitutionId" bigint NOT NULL,
    "StaffTeachingAssignmentId" bigint NOT NULL, "PlannedDate" date NOT NULL, "PeriodReference" varchar(80),
    "Objectives" varchar(2000) NOT NULL, "TeachingMethod" varchar(1000), "Resources" varchar(1000), "Activities" varchar(2000), "Assessment" varchar(1000), "Homework" varchar(1000),
    "WorkflowStatusId" smallint NOT NULL, "ReviewedById" bigint, "ReviewedDateTime" timestamp without time zone, "ReviewRemark" varchar(500),
    "IsActive" boolean NOT NULL DEFAULT true, "IsSoftDeleted" boolean NOT NULL DEFAULT false,
    "AddedById" bigint NOT NULL, "AddedDateTime" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "UpdatedById" bigint, "UpdatedDateTime" timestamp without time zone,
    CONSTRAINT "FK_LessonPlan_Assignment" FOREIGN KEY ("StaffTeachingAssignmentId") REFERENCES skolenza."StaffTeachingAssignment"("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_LessonPlan_Status" FOREIGN KEY ("WorkflowStatusId") REFERENCES skolenza."AcademicWorkflowStatusMaster"("Id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS skolenza."LessonPlanCurriculumTopic" (
    "LessonPlanId" bigint NOT NULL, "CurriculumTopicId" bigint NOT NULL,
    PRIMARY KEY ("LessonPlanId", "CurriculumTopicId"),
    CONSTRAINT "FK_LessonPlanTopic_Plan" FOREIGN KEY ("LessonPlanId") REFERENCES skolenza."LessonPlan"("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_LessonPlanTopic_Topic" FOREIGN KEY ("CurriculumTopicId") REFERENCES skolenza."CurriculumTopic"("Id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS skolenza."LessonDeliveryLog" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "InstitutionId" bigint NOT NULL, "LessonPlanId" bigint NOT NULL,
    "DeliveredDate" date NOT NULL, "CoverageNotes" varchar(2000) NOT NULL, "Homework" varchar(1000), "EvidenceReference" varchar(500), "ExceptionReason" varchar(1000), "ReplanAction" varchar(1000),
    "WorkflowStatusId" smallint NOT NULL, "ReviewedById" bigint, "ReviewedDateTime" timestamp without time zone, "ReviewRemark" varchar(500),
    "IsActive" boolean NOT NULL DEFAULT true, "IsSoftDeleted" boolean NOT NULL DEFAULT false,
    "AddedById" bigint NOT NULL, "AddedDateTime" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "UpdatedById" bigint, "UpdatedDateTime" timestamp without time zone,
    CONSTRAINT "FK_LessonDelivery_Plan" FOREIGN KEY ("LessonPlanId") REFERENCES skolenza."LessonPlan"("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_LessonDelivery_Status" FOREIGN KEY ("WorkflowStatusId") REFERENCES skolenza."AcademicWorkflowStatusMaster"("Id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS skolenza."LessonDeliveryCoverage" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "LessonDeliveryLogId" bigint NOT NULL, "CurriculumTopicId" bigint NOT NULL, "CompletionPercent" numeric(5,2) NOT NULL,
    CONSTRAINT "FK_LessonCoverage_Log" FOREIGN KEY ("LessonDeliveryLogId") REFERENCES skolenza."LessonDeliveryLog"("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_LessonCoverage_Topic" FOREIGN KEY ("CurriculumTopicId") REFERENCES skolenza."CurriculumTopic"("Id") ON DELETE RESTRICT,
    CONSTRAINT "UQ_LessonCoverage_Log_Topic" UNIQUE ("LessonDeliveryLogId", "CurriculumTopicId"),
    CONSTRAINT "CK_LessonCoverage_Percent" CHECK ("CompletionPercent" BETWEEN 0 AND 100)
);

CREATE INDEX IF NOT EXISTS "IX_CurriculumFramework_Institution" ON skolenza."CurriculumFrameworkMaster" ("InstitutionId");
CREATE INDEX IF NOT EXISTS "IX_CurriculumUnit_Institution_Framework" ON skolenza."CurriculumUnit" ("InstitutionId", "CurriculumFrameworkId");
CREATE INDEX IF NOT EXISTS "IX_CurriculumTopic_Institution_Unit" ON skolenza."CurriculumTopic" ("InstitutionId", "CurriculumUnitId");
CREATE INDEX IF NOT EXISTS "IX_LessonPlan_Institution_Date" ON skolenza."LessonPlan" ("InstitutionId", "PlannedDate");
CREATE INDEX IF NOT EXISTS "IX_LessonDelivery_Institution_Date" ON skolenza."LessonDeliveryLog" ("InstitutionId", "DeliveredDate");

COMMIT;
