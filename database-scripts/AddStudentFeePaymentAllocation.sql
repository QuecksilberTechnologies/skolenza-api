-- Additive allocation ledger. Existing payments are not assigned to fee heads.
BEGIN;
LOCK TABLE skolenza."StudentAdmissionFeeQuote", skolenza."StudentFeeInstallmentHead",
    skolenza."StudentFeePaymentTransaction" IN SHARE MODE;
DO $$
BEGIN
    IF to_regclass('skolenza."StudentFeePaymentAllocation"') IS NULL
       AND (EXISTS (SELECT 1 FROM skolenza."StudentAdmissionFeeQuote")
            OR EXISTS (SELECT 1 FROM skolenza."StudentFeePaymentTransaction")
            OR EXISTS (SELECT 1 FROM skolenza."StudentFeeInstallmentHead")) THEN
        RAISE EXCEPTION 'Existing quotes or payments require an explicitly verified allocation migration.';
    END IF;
END $$;
ALTER TABLE skolenza."StudentFeeInstallmentHead"
    ADD COLUMN IF NOT EXISTS "AllocationPriority" smallint NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "AK_StudentFeeInstallmentHead_TenantInstallment"
    ON skolenza."StudentFeeInstallmentHead" ("Id", "InstitutionId", "StudentFeeInstallmentId");
CREATE UNIQUE INDEX IF NOT EXISTS "AK_StudentFeePaymentTransaction_TenantInstallment"
    ON skolenza."StudentFeePaymentTransaction" ("Id", "InstitutionId", "StudentFeeInstallmentId");
CREATE TABLE IF NOT EXISTS skolenza."StudentFeePaymentAllocation" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InstitutionId" bigint NOT NULL,
    "StudentFeeInstallmentId" bigint NOT NULL,
    "StudentFeePaymentTransactionId" bigint NOT NULL,
    "StudentFeeInstallmentHeadId" bigint NULL,
    "Amount" numeric(18,3) NOT NULL,
    CONSTRAINT "CK_StudentFeePaymentAllocation_Amount" CHECK ("Amount" > 0),
    CONSTRAINT "FK_StudentFeePaymentAllocation_Payment"
        FOREIGN KEY ("StudentFeePaymentTransactionId", "InstitutionId", "StudentFeeInstallmentId")
        REFERENCES skolenza."StudentFeePaymentTransaction" ("Id", "InstitutionId", "StudentFeeInstallmentId") ON DELETE RESTRICT,
    CONSTRAINT "FK_StudentFeePaymentAllocation_Head"
        FOREIGN KEY ("StudentFeeInstallmentHeadId", "InstitutionId", "StudentFeeInstallmentId")
        REFERENCES skolenza."StudentFeeInstallmentHead" ("Id", "InstitutionId", "StudentFeeInstallmentId") ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_StudentFeePaymentAllocation_Head"
    ON skolenza."StudentFeePaymentAllocation" ("StudentFeePaymentTransactionId", "StudentFeeInstallmentHeadId")
    WHERE "StudentFeeInstallmentHeadId" IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "UX_StudentFeePaymentAllocation_LateFee"
    ON skolenza."StudentFeePaymentAllocation" ("StudentFeePaymentTransactionId")
    WHERE "StudentFeeInstallmentHeadId" IS NULL;
COMMIT;
